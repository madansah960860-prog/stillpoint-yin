<h1>Editorial Policy</h1>
<p class="lede">This page sets out how content on www.stillpointyin.com is made and who is accountable for it. It exists because a reader deciding whether to trust a website deserves to know the answer rather than guess at it.</p>
<p class="stamp">Last updated 1 September 2026.</p>

<h2>Who writes this site</h2>
<p>Stillpoint Yin & Meditation is written by named people. Rosalind Vega, founder and the only teacher, is the editor and writes the majority of what appears here. There is no second writer. Rosalind writes everything here, and where a piece touches anatomy or physiology it is read before publication by Dr. Priya Anand, a physical therapist in Long Island City who has no financial interest in this studio and is paid an hourly rate for the reading.</p>
<p>Every substantial page carries the name of the person who wrote it. Where a page was written by one person and reviewed by another, both names appear. We do not publish under a house byline, we do not invent contributor personas, and there is no artificial intelligence writing the words on this site.</p>
<h2>How a class description or article is made</h2>
<p>Everything published here begins in the room. A class description is written after the class has been taught repeatedly, by the person who teaches it, and it describes what actually happens in that hour rather than what would sound appealing in a brochure. If a class is hard, the description says so.</p>
<p>Articles about practice follow a fixed route. A teacher drafts from their own teaching experience. Where the draft touches anatomy, physiology, contraindications or the history of a tradition, it is checked against sources: peer-reviewed literature where it exists, established anatomical references, and primary or well-regarded translations for textual claims. Where the evidence is thin, the article says the evidence is thin. That sentence appears more often than readers expect, because in yoga research it is frequently the honest one.</p>
<p>A second teacher reads every draft before it is published, looking specifically for instructions that would be unsafe without supervision and for claims that overreach.</p>

<h2>Claims we will not make</h2>
<ul>
  <li>That a posture, a sequence or a breath practice cures, treats or prevents a disease.</li>
  <li>That yoga is a substitute for medical treatment, physical therapy or psychological care.</li>
  <li>That a particular practice will produce a particular body, weight or appearance.</li>
  <li>That any tradition on offer here is the single authentic version of yoga.</li>
  <li>Anything with a number in it that we have not read the study for.</li>
</ul>

<h2>Independence from advertising</h2>
<p>The advertising on this site is served automatically and nobody here sees an advertiser's name before it appears. No advertiser has ever been shown a draft, has ever suggested a topic, or has any right of review over anything published. If that changed, this page would change with it and the arrangement would be disclosed on the page in question. Our <a href="advertising-disclosure.php">Advertising Disclosure</a> covers the commercial side in detail.</p>

<h2>Sources and attribution</h2>
<p>Where we rely on someone else's work we say so and link to it. Quotations are short, marked and attributed. Photographs are credited in the image credits file that ships with the site, each with a source link and its license. Where an idea came from a particular teacher, book or region, that lineage is named, because pretending otherwise is both dishonest and duller.</p>

<h2>Corrections</h2>
<p>We correct mistakes rather than quietly deleting them. The scale of the response matches the scale of the error.</p>
<ul>
  <li><strong>Typographical and formatting errors</strong> are fixed on sight without a note.</li>
  <li><strong>Factual errors that change the meaning</strong> are fixed, and a dated correction line is added at the foot of the page saying what was wrong and what it now says.</li>
  <li><strong>Errors that could cause harm</strong>, such as a wrong temperature, a wrong quantity or an unsafe instruction, are fixed immediately, flagged at the top of the page, and the page is re-checked from the beginning.</li>
  <li><strong>Articles that are simply out of date</strong> are either updated with a new review date or retired with a note explaining why.</li>
</ul>

<h2>How to request a correction</h2>
<p>Email <a href="mailto:rosalind@stillpointyin.com">rosalind@stillpointyin.com</a> with the page address and the specific sentence you think is wrong. If you have a source, include it. We acknowledge correction requests within three business days and act on valid ones within seven. If we disagree with you we will say so and explain why rather than ignore the message. If you were right, the correction line will say that a reader pointed it out, and you are welcome to be named or to stay anonymous as you prefer.</p>

<h2>Review cycle</h2>
<p>Published pages are reviewed on a rolling basis, with the practical pages that people act on prioritized over the reflective ones. Each reviewed page carries the date it was last checked. A review date is not decoration: it means somebody read the page again with fresh eyes and confirmed that it still says what it should.</p>
