<h2>This site does not give medical advice</h2>
<p>Stillpoint Yin & Meditation publishes descriptions of classes, accounts of practice, and general writing about yoga and breathing. None of it is medical advice, physical therapy, psychotherapy or a diagnosis, and none of it is a substitute for a consultation with a qualified healthcare professional who has examined you. Our teachers are yoga teachers. Several hold additional qualifications, and those are listed honestly on the teachers page, but in the context of this website none of them is acting as your clinician.</p>

<h2>Consult a doctor first</h2>
<p>Speak to a doctor or another suitably qualified healthcare professional before starting yoga, before returning to it after a break, and before continuing with it if your circumstances change. This matters particularly if any of the following apply to you.</p>
<ul>
  <li>You are pregnant, have recently given birth, or are being treated for a condition related to pregnancy.</li>
  <li>You have high or low blood pressure, a heart condition, or a history of stroke.</li>
  <li>You have glaucoma, a detached retina, or any condition affecting intraocular pressure.</li>
  <li>You have a disc injury, spinal instability, osteoporosis or osteopenia, or have had spinal surgery.</li>
  <li>You have had a joint replacement, a recent fracture, or any surgery within the last six months.</li>
  <li>You have epilepsy, vertigo, or a condition affecting balance.</li>
  <li>You are taking medication that affects blood pressure, heart rate, balance, coordination or perception of pain.</li>
  <li>You are recovering from illness, or are undergoing treatment that affects your energy or your immune system.</li>
</ul>

<h2>Practice within your own limits</h2>
<p>Nobody on this website can see you. We cannot see your alignment, we do not know your history, and we have no way of telling whether a shape that is safe for the person in the photograph is safe for you today. You are responsible for judging what is appropriate for your own body. Work at an intensity you can sustain while breathing normally. Come out of a position if you feel sharp pain, numbness, tingling, dizziness, nausea, chest pain or breathlessness, and do not go back into it in the same session.</p>
<p>Discomfort and pain are not the same thing. A long hold in a stretch may be uncomfortable; that is ordinary. Pain at a joint, pain that is sharp, pain that radiates, and pain that persists afterwards are all signals to stop and to seek advice.</p>

<h2>Breathing practices</h2>
<p>Breath practices are not neutral. Retention, rapid breathing and forceful exhalation change blood chemistry and can provoke dizziness, fainting, panic and, in susceptible people, seizures. Do not practice breath retention if you are pregnant, if you have high blood pressure, cardiovascular disease, epilepsy or a history of panic attacks, or if you are under the influence of alcohol or any sedating drug. Never practice breath retention in or near water. If a breathing practice makes you feel strange, stop and breathe normally.</p>

