<h2>The thing nobody mentions</h2>
<p>You arrive having crossed the city. Your attention has been in twenty places in the last hour.
You lie down on a mat in a dark room and are asked to do nothing, and within about four minutes
something quite unpleasant happens.</p>
<p>It is not physical. It is the arrival of everything you had been outrunning. The unanswered
message, the conversation that went badly, the thing you said in a meeting in 2019. In a fast
class this does not occur, because there is no room for it. In a slow one it is the first thing
through the door.</p>
<p>I would put it at ten minutes. Ten minutes of restlessness, mild dread, and an extremely
persuasive internal case that this was a poor use of an evening. Then, for most people, it lifts.</p>

<h2>Why the beginning specifically</h2>
<p>Three things stack up at the start of a class and then stop stacking.</p>
<p><strong>The contrast is at its sharpest.</strong> The gap between the speed you were traveling at
ten minutes ago and the speed you are being asked to travel at now is widest in the first stretch, and
narrows on its own.</p>
<p><strong>Nothing has happened yet.</strong> Ten minutes in, you have no evidence that the class is
going to be worth it. Fifty minutes in, you have some.</p>
<p><strong>The body is still cataloguing.</strong> The first few minutes of lying still are when you
find out what hurts today. That inventory is uncomfortable and it finishes.</p>

<h2>What does not help</h2>
<p>Trying to relax. This is the instruction most often given and it is close to useless, because
relaxing is not a thing you can do on purpose; it is a thing that happens when the conditions are
right. Being told to relax mostly adds a task.</p>
<p>Deciding the restlessness means you are bad at this. It is the most common interpretation and it
is wrong. The people I know with the deepest practices describe exactly the same ten minutes.
They have simply stopped treating it as information about themselves.</p>
<p>Leaving. Obviously you may leave, and the door is not locked, but leaving at minute eight teaches
you that the feeling is unsurvivable, and it is not.</p>

<h2>What does help</h2>
<p><strong>Knowing it is coming.</strong> This is most of it. The students who get through the first
month are almost always the ones who were told in advance that the opening stretch is the hard part.</p>
<p><strong>Having something small to do.</strong> Count exhales to ten, then start again. Not as a
meditation technique but as a handhold for exactly the period in which you need one. Drop it once the
class settles.</p>
<p><strong>Arriving earlier.</strong> Five minutes lying on the mat before the class starts, in the
dark, with nobody talking, moves some of the ten minutes to before the beginning, where it costs less.</p>
<p><strong>Staying warm.</strong> Genuinely. A cold body will not settle, and half the restlessness I
see in the first ten minutes of a Friday restorative class is somebody who needs a second blanket and
has not liked to ask. Ask.</p>

<h2>The measure that actually matters</h2>
<p>Not whether the class felt good. Almost nobody's first class feels good, and quite a few of my own
do not, thirteen years in.</p>
<p>The measure is how you are at ten the following morning, and whether you come back. Come three
times before deciding anything. The first is mostly logistics and the second is usually worse than
the first, because the novelty has gone. The third is where people find out whether this is for them.</p>
<p>And if after three it is not, that is a perfectly good outcome, honestly arrived at. There are four
excellent fast studios within a fifteen-minute walk and I will happily tell you which one to try.</p>
