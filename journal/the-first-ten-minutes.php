    <h1>The first ten minutes are the worst</h1>
    <p class="byline">Rosalind Vega, <time datetime="2026-06-18">18 June 2026</time>. Read
      before publication by Dr. Priya Anand.</p>
    <p class="lede">People do not stop coming because the practice is too hard. They stop because of a specific unpleasant stretch at the start of a class, which almost nobody warns them about.</p>
  </div>
</article>
<div class="column"><div class="ad-slot ad-slot--incontent"></div></div>
