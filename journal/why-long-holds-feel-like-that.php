    <h1>Why long holds feel like that</h1>
    <p class="byline">Rosalind Vega, <time datetime="2026-08-02">2 August 2026</time>. Read
      before publication by Dr. Priya Anand.</p>
    <p class="lede">Four minutes in a supported hip shape produces something that most people describe, unprompted, in almost the same words. The sensation is real. The explanation normally attached to it is not as solid as it is made to sound.</p>
  </div>
