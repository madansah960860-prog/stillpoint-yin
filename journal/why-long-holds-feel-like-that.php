<h2>What people report</h2>
<p>Ask a room of twelve people what a four-minute hold felt like and you get a strikingly
consistent account. For the first ninety seconds, a broad dull stretch, unremarkable. Then a
build, described as spreading or filling. Somewhere around two and a half to three minutes,
a shift: the sensation either moves to a slightly different place, or changes from sharp-edged
to diffuse, or simply becomes less interesting. And then, for the last minute, most people say
they stopped noticing it.</p>
<p>That arc is the practice. Everything else in a yin class is arrangement.</p>

<h2>The explanation you will usually hear</h2>
<p>That long static holds load fascia — the connective tissue that wraps and separates muscle —
and that because fascia is slow to respond, three minutes is the minimum dose to change it. You
will often hear a number attached: ninety seconds, or two minutes, or three, given as though it
came from somewhere specific.</p>
<p>I taught this for two years. I no longer do, and it is worth explaining why rather than quietly
dropping it.</p>

<h2>Where that account gets thin</h2>
<p>The fascia research that gets quoted in yoga rooms is mostly one of three kinds. Studies on
cadaver tissue, which tells you about the mechanical properties of dead tissue under load and not
about what happens in a living hip. Studies in cell culture, where fibroblasts are stretched in a
dish and change their behavior, which is genuinely interesting and several steps removed from a
person on a bolster. And imaging studies in living humans that are small, short and often without
a control group.</p>
<p>None of that is fraudulent and none of it is worthless. It simply does not support the confident
sentence "a three-minute hold remodels your fascia", and the specific time thresholds quoted in
classes do not appear to come from any study at all. When I went looking for the origin of the
ninety-second figure, I found it cited in books that cited other books.</p>
<p>There is also a simpler problem. Whatever is being loaded in a long hold, it is certainly not
only fascia. Muscle, tendon, ligament, joint capsule and nerve are all in there, and the nervous
system is interpreting the whole package.</p>

<h2>A more defensible account</h2>
<p>Here is what I think can be said without overreaching, and what Dr. Anand let through when she
read this.</p>
<p><strong>Stretch tolerance changes faster than tissue does.</strong> This is well established in
the flexibility literature and it is probably the largest single contributor to what you feel. Held
at a constant length, the sensation you experience declines, not because the tissue has lengthened
but because your nervous system has recalibrated how much alarm the position warrants. That
recalibration happens over seconds to minutes, which fits the arc above almost exactly.</p>
<p><strong>Sustained, unstimulating input lowers arousal.</strong> Lying still in low light, breathing
slowly, with nothing to attend to but one steady sensation, is a fairly reliable way to shift the
autonomic balance. That is not mystical and it does not need connective tissue to explain it.</p>
<p><strong>The three-minute shift is likely perceptual, not structural.</strong> Something changes at
around three minutes for most people. The likeliest explanation is that attention gets bored, which
is a less romantic sentence than the fascia one and considerably easier to defend.</p>

<h2>Does this make the practice less worthwhile?</h2>
<p>Students ask this, usually looking slightly deflated, and the answer is no. It makes the claims
smaller and the practice exactly the same size.</p>
<p>A practice that reliably lowers arousal on a Wednesday evening, that trains you to stay in contact
with a safe but uncomfortable sensation without immediately escaping it, and that gives you seventy-five
minutes in which nothing is being asked of you, does not need to be remodelling anything to be worth
your time. I would rather teach that honestly than teach something grander that I cannot defend.</p>

<h2>What this changes in the room</h2>
<p>Very little, practically. The holds are still three to five minutes, because that is how long the
arc takes. The props still do the work. What changes is the language: I no longer tell you what your
fascia is doing, because I do not know.</p>
<p>What I do say is come out if it is sharp, if it is at a joint line, if it radiates, or if anything
goes numb. That instruction is not a matter of interpretation and it is the only one that really
matters.</p>
