<h2>Why people ask</h2>
<p>Of the students who tell me why they started, sleep is the most common answer by a wide margin.
Usually the account is the same: fine until about two in the morning, then awake, with a mind that
has decided now is the time to review everything.</p>
<p>It would be easy to sell to. I am not going to, and this page exists mainly so that I have
somewhere to point when the question comes up before a class and there are three minutes to answer it.</p>

<h2>What the evidence reasonably supports</h2>
<p>Slow, low-intensity movement practices — yin, restorative, gentle hatha, tai chi — show modest
improvements on standard sleep questionnaires in a fair number of trials, particularly in older adults
and in people with insomnia symptoms. Slow breathing at around six breaths a minute improves measures
of autonomic balance, and doing it before bed shortens self-reported time to fall asleep in several
small studies.</p>
<p>Those findings are consistent enough to take seriously and weak enough to describe carefully. The
trials are mostly small. They almost never blind anybody, which is difficult when the intervention is
lying on a bolster. Most rely on self-report rather than on sleep measured in a laboratory, and self-report
is exactly the measure most affected by expecting something to help.</p>
<p>So: real, modest, and softer than the headlines.</p>

<h2>What it does not support</h2>
<p>That yoga treats insomnia. That it addresses sleep apnoea, which is a mechanical problem and needs a
clinician. That any breathing technique will reliably put you to sleep in sixty seconds. That an evening
class will fix sleep disrupted by shift work, a new baby, pain, grief, menopause, alcohol, or a diagnosed
mood disorder — all of which are far more powerful inputs than anything that happens in this room.</p>
<p>If you are consistently sleeping badly for more than a few weeks, the correct next step is a doctor, not
a yoga studio. That is not modesty. Chronic poor sleep has causes worth identifying, and a nice evening
class is a very good way to spend six months not identifying them.</p>

<h2>The mechanism that is probably doing the work</h2>
<p>Most likely, nothing exotic. Seventy-five minutes in low light with no screen, at a fixed time, with
slow breathing and nothing demanded of you, is a large intervention in the conditions around sleep even if
it is a small one in physiology.</p>
<p>Consider what an evening class displaces. It removes an hour and a half of bright screen in the window
before bed. It puts a predictable marker at the same point in the evening, which regular timing is one of
the few sleep interventions with strong evidence behind it. It gets you walking to and from a room. And it
gives a busy mind ninety minutes of practice at not chasing every thought, which is precisely the skill
that fails at two in the morning.</p>
<p>That is a decent list. It is also a list about behavior and routine rather than about fascia or energy,
and I think it is the honest account.</p>

<h2>What I suggest, with the caveats attached</h2>
<p>Come to a restorative class rather than a yin one if sleep is the reason. It is stiller and it finishes
later.</p>
<p>Do the eleven-minute home version on the nights you do not come, at the same time each night. Consistency
is worth more than duration and considerably more than intensity.</p>
<p>Practice extending the exhale, in bed, if you wake at two: in for four, out for six, easy on both ends,
and no counting past ten. It may or may not return you to sleep. What it reliably does is give the mind a
task that is not reviewing your life.</p>
<p>And keep a sense of proportion about the whole thing. Several students have told me their sleep improved
after a few months here. I believe them, and I have no way of knowing whether it was the practice, the
routine, the walk, the winter ending, or the fact that they were doing something about it at all. Neither
does anybody selling you a course that promises otherwise.</p>
