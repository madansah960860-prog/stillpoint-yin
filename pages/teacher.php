<section class="quiet">
  <div class="column">
    <figure>
      <img src="../assets/images/teacher/teacher-rosalind-vega.jpg"
           alt="Rosalind Vega, founder and teacher at Stillpoint, photographed in soft low light with her eyes closed"
           width="640" height="800" loading="lazy" decoding="async">
      <figcaption>Photographed in the studio on a Tuesday, about an hour before the room
        filled up.</figcaption>
    </figure>
    <p>I came to this the way a lot of people come to slow practice, which is to say through
      an injury and a fairly unpleasant year.</p>
    <p>For most of my twenties I taught vinyasa, six classes a week, in three studios across
      north Brooklyn and one in Manhattan that I will not name. I was good at it in the way
      that being energetic and reasonably strong makes you good at it. In 2017 I tore the
      labrum in my right hip, which is an injury you get from repeatedly taking a joint to its
      end range with enthusiasm, and which took eighteen months and an operation to resolve.</p>
    <p>For about nine months of that I could not do anything I recognized as yoga. What I could
      do was lie on the floor with a bolster under my knees. So I did that, for a long time, in
      the evenings, and somewhere in the middle of it the thing I had been performing for a decade
      turned into something I was actually doing.</p>
    <p>I trained in yin with Sarah Powers' lineage in 2018 and 2019, and in restorative practice
      with Judith Hanson Lasater's program the following year. Both of those are real trainings
      with real hours attached and I will happily show you the certificates, which live in a
      drawer where certificates belong.</p>
    <p>More usefully, I spent two years afterward reading the actual research on connective tissue,
      because I had been repeating claims in class that I could not have defended if anybody had
      pressed me. What I found was that a good deal of it does not hold up. That is now a thing I
      say out loud in class, which some students find deflating for about a week and then
      clarifying.</p>

    <h2>How I teach</h2>
    <p>Quietly, and less than most teachers. A yin class here contains perhaps thirty sentences
      in seventy-five minutes. I do not narrate, I do not offer a theme, and I do not read poetry
      at you in savasana.</p>
    <p>I give the timing out loud, always, because not knowing how long is left is the single
      biggest source of tension in a long hold. I offer the propped version of a shape first and
      the deeper version second, in that order, so that taking the supported option is not a visible
      act of opting down.</p>
    <p>I do not touch anybody without consent, I do not touch anybody at all in a first class, and
      the small stone beside your mat means you can change your mind silently and mid-shape.</p>

    <h2>What I will not tell you</h2>
    <p>That a posture detoxifies an organ. That holding a hip shape releases stored emotion in
      any literal sense, though people do sometimes cry in hip shapes and that is worth talking
      about honestly rather than mystically. That this practice will cure your insomnia, your
      back, or your anxiety. That there is an authentic version of yin, a tradition roughly forty
      years old and assembled in California.</p>
    <p>I am not a doctor, a physical therapist, or a therapist of any other kind, and none of what
      happens in this room is treatment. When somebody describes something to me that needs a
      clinician, I say so and stop talking.</p>
  </div>
</section>

