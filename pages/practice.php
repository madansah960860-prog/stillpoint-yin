    <h2>Restorative</h2>
    <p>Restorative is not slow yin. It is a different practice with a different aim, and
      confusing the two is the most common mistake people bring into the room.</p>
    <p>In yin there is sensation, on purpose. In restorative there should be almost none. Each
      shape is propped until it holds itself: bolsters under the knees, a folded blanket under
      the head, a second blanket over the whole of you, an eye covering if you want one. Then
      you stay for eight to twelve minutes, and the only instruction is to stop holding on.</p>
    <p>Ninety minutes contains five or six of these. The room is at its darkest for this class.
      I speak perhaps four times in the whole session, usually to say how long is left, because
      not knowing how long is left turns out to be the single thing that keeps people tense.</p>
    <p>People fall asleep. Roughly a third of the room on a Friday. This is neither a failure
      nor the goal, and nobody gets woken up; the class ends, the lights come up one notch, and
      whoever is asleep wakes when they wake.</p>
  </div>
</section>

<section class="quiet quiet--slate">
  <div class="column">
    <h2>Breath and sitting</h2>
    <p>Sixty minutes, twice a week, and the plainest thing on the schedule. Twenty-five minutes
      of slow breathing, thirty minutes of sitting, and about five minutes at the end where
      nothing is asked of you at all.</p>
    <p>The breathing is limited to three practices. Extending the exhale until it is longer
      than the inhale. Even-count breathing with no pause at either end. And alternate nostril
      breathing taught slowly, without retention, mostly because it gives the hands something
      to do and makes the breath narrow by itself.</p>
    <div class="note">
      <h3>What is not taught in this room</h3>
      <p>No breath retention. No rapid or forceful breathing. No counting anybody into a hold.
        These practices are genuinely powerful and genuinely risky: they change blood chemistry,
        and they are contraindicated in pregnancy, in uncontrolled high blood pressure, in
        cardiovascular disease, in epilepsy, in glaucoma, and in anyone with a history of panic
        attacks, for whom air hunger is frequently the trigger. Fainting is common enough to
        have a name.</p>
      <p>A drop-in class is a room full of people whose histories I do not know. So they are
        not taught here at all. If you want to learn them, learn them one to one with somebody
        who does know your history, and read the
        <a href="../policies/disclaimer.php">disclaimer</a> first.</p>
    </div>
    <p>The sitting is unguided after the first two minutes. No visualization, no body scan, no
      voice in your ear. You will find this either a relief or intolerable and you will know
      which within one session.</p>
  </div>
</section>

