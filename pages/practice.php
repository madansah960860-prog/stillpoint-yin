    <h1>The practice</h1>
    <p class="lede">Three formats, described at the length they deserve rather than at the
      length that fits a tile. If you read one page on this site before coming, read this one.</p>
  </div>
</section>

<section class="quiet quiet--slate">
  <div class="column">
    <h2>Yin</h2>
    <p>A yin class is seventy-five minutes and contains perhaps six shapes. All of them are
      on the floor. All of them are held between three and five minutes without moving, and
      the holds are timed, so nobody has to wonder how much longer.</p>
    <p>The muscles are deliberately not engaged. That is the defining feature and it is what
      separates yin from every other kind of stretching. You come into a shape at maybe sixty
      per cent of your available range, you let props take the rest of the weight, and then
      you stop working. What is left is a slow, dull, spreading sensation somewhere in the
      hip or the low back, which builds for about ninety seconds, plateaus, and then usually
      changes character entirely at around the three-minute mark.</p>
    <p>The claim normally attached to this is that long holds remodel fascia, the connective
      tissue that wraps and separates everything else. That may be partly true. The honest
      position is that the evidence in living humans is thin, that most of the fascia research
      quoted in yoga rooms was done on cadaver tissue or in a dish, and that nobody has
      convincingly demonstrated the mechanism in a person lying on a mat in Brooklyn.</p>
    <p>What is better supported, and what I actually teach toward, is duller and more useful:
      long unstimulating holds reliably lower arousal, and a practice that puts you in
      sustained contact with an uncomfortable-but-safe sensation is good training for the
      more general skill of not immediately fleeing discomfort. That is worth seventy-five
      minutes on a Wednesday. It does not need a fascia diagram.</p>
  </div>
</section>

