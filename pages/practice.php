<section class="quiet">
  <div class="column">
    <h2>What a session is actually like</h2>
    <p>You arrive and the room is already dark. There are eleven candles along the north wall
      and one lamp near the door, and that is the whole of the lighting. Twelve mats are already
      laid out with a bolster, two blocks and two folded blankets on each, because setting up
      props in the dark while other people are lying down is no way to begin.</p>
    <p>I ask two questions at the start of every class, to the room rather than to individuals.
      Whether anyone is pregnant or has anything that has changed since last time, and whether
      anyone would rather not be touched. The second question has a small stone beside each mat:
      dark side up means no hands. You can turn it over mid-class without saying anything.</p>
    <p>Then the class starts and very little happens for seventy-five minutes, which is the
      point. There is no music with words. There is no playlist at all in restorative. In yin
      there is sometimes something very quiet and instrumental, and if it is distracting you may
      say so and it goes off.</p>
    <p>At the end I say the time, and people leave when they are ready. Some leave immediately.
      Some sit against the wall for ten minutes. The door is unlocked either way and there is
      hot water and tea on the landing.</p>

    <h2>What to wear and bring</h2>
    <p>Long sleeves and long trousers, something soft, nothing with a rigid waistband, because
      you will spend an hour folded over. Socks, or borrow a pair. Something to tie hair back,
      because a lot of this is face-down.</p>
    <p>Bring nothing else. Mats, bolsters, blocks, straps, blankets and eye coverings are all
      here and are washed on a rotation that Rosalind is unreasonably strict about.</p>

    <h2>Who this is not for</h2>
    <p>If you are looking for a workout, this is not it and you will be bored. If you want
      technical alignment instruction, go to an Iyengar room, where they do it properly.</p>
    <p>If you are in acute pain, recently injured, or recovering from surgery, do not start
      here without talking to a doctor first, and then tell me before class rather than after.
      Long unsupervised holds are not automatically gentle; four minutes in a deep hip shape can
      aggravate a sacroiliac joint quite efficiently. And if you are pregnant, write to me before
      your first class so the props are already set up differently when you arrive.</p>
  </div>
</section>

