    <h2>Before you book</h2>
    <p>Come to at least two ordinary yin classes first. Not as a rule, and nobody checks, but
      people who arrive at week one having never held a shape for four minutes spend the first
      evening in a kind of shock and it is a waste of their money.</p>
    <p>The course is not suitable if you are in acute pain or in the first weeks of recovery
      from an injury or an operation, and it is not designed for pregnancy, though a modified
      version of every session exists and has been run twice. Write and ask. The
      <a href="../policies/disclaimer.php">disclaimer</a> covers the general position
      and is worth five minutes of your time.</p>
    <p>Refunds are given in full up to a week before the course starts, and at half after that
      if the place can be filled from the waiting list, which it usually can.</p>
