    <h1>Learning to Stay</h1>
    <p class="lede">A six-week course, Sunday evenings, twelve people. The only thing here
      that runs in a fixed order, because it is a real sequence and week four genuinely does
      not work before week three.</p>
  </div>
</section>

<section class="quiet quiet--slate">
  <div class="column">
    <p>The course exists because a drop-in class cannot teach this. In a drop-in room there
      is always somebody who has never held a shape for four minutes, so the instruction is
      always pitched at them, and the people in their second year never get the next thing.</p>
    <p>Six evenings, two hours each, the same twelve people throughout. The room is the same
      room, the candles are the same candles, and the only difference is that we stop and talk,
      which does not happen in a normal class.</p>
    <p>It is not a teacher training and it will not qualify you for anything. Nobody gets a
      certificate. What you get is a practice you can do at home on a Tuesday in February when
      you do not feel like it, which is the only measure of a course like this that means
      anything.</p>
  </div>
</section>

<section class="quiet">
  <div class="column">
    <h2>The six weeks</h2>
    <ol class="sequence">
      <li>
        <h3>Staying for four minutes</h3>
        <p>The whole first evening is spent on three shapes and nothing else. We time them together, out loud, so that everyone learns what four minutes actually feels like, which is considerably longer than anyone estimates. We talk about the difference between sensation and pain, and about the specific signals that mean come out now: sharpness, anything at a joint line, anything radiating, numbness, pins and needles.</p>
        <p class="sequence__meta">Two hours. Three shapes. A great deal of talking, which will not be true of week five.</p>
      </li>
      <li>
        <h3>Where the sensation is coming from</h3>
        <p>An honest hour on anatomy, which means a shorter hour than you might expect, because a lot of what gets said about connective tissue in yoga rooms is not well supported. We cover what tissue is plausibly being loaded in a long hold, what the current evidence does and does not show, and why the sensation moves and changes at around three minutes. Dr. Priya Anand joins this session most terms and contradicts me at least twice, which is why she is invited.</p>
        <p class="sequence__meta">Two hours, roughly half of it practical.</p>
      </li>
      <li>
        <h3>Restlessness</h3>
        <p>The practical subject of the course. Somewhere in the second or third minute the mind produces a list of reasons to move, and the list is extremely persuasive. We work with that directly: naming it, waiting it out, and distinguishing between the restlessness that should be sat through and the discomfort that should be respected. This is the week that changes people's home practice.</p>
        <p class="sequence__meta">Two hours, mostly practice, with a long conversation at the end.</p>
      </li>
      <li>
        <h3>Slow breathing, properly</h3>
        <p>Extending the exhale. Even-count breathing. Alternate nostril breathing taught at quarter speed. What each one plausibly does, on what evidence, and what is overclaimed about all three. No retention is taught, here or anywhere in this studio, and the reasons are given in full rather than asserted.</p>
        <p class="sequence__meta">Two hours. Bring a chair-friendly attitude; sitting on the floor is not required.</p>
      </li>
      <li>
        <h3>Thirty minutes of sitting</h3>
        <p>The week people most often dread and most often report back about. We build from ten minutes to thirty across the evening, with breaks. There is no technique beyond an anchor at the start, because the point of the course is not to give you a method but to show you that the thirty minutes is survivable without one.</p>
        <p class="sequence__meta">Two hours, of which around seventy minutes is sitting in total.</p>
      </li>
      <li>
        <h3>The evening you do not feel like it</h3>
        <p>Home practice, and the reason most home practice fails. We build a version that takes eleven minutes, works on a bedroom floor with a rolled towel instead of a bolster, and survives contact with a bad week. Everyone leaves with a single printed card, and there is no app, no login, no follow-up sequence and nothing to subscribe to.</p>
        <p class="sequence__meta">Two hours, and then tea, and then it is over.</p>
      </li>
    </ol>
  </div>
</section>

