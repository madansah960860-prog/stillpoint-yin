    <p><strong>By bike.</strong> There is a rack outside the laundromat and a Citi Bike dock at
      the corner of Java and Franklin.</p>
    <p><strong>By car.</strong> Street parking only, and it is genuinely difficult after six in
      the evening, which is when all of our classes are. Most people take the G.</p>
    <p><strong>The door.</strong> Black, no sign, immediately left of the laundromat entrance.
      It is on the latch from twenty minutes before each class and locked at ten minutes past
      the hour, because the stairwell is shared with two apartments.</p>

