    <h2>Access, described honestly</h2>
    <p>The studio is up one flight of stairs, eighteen steps, with a handrail on the right. There
      is no elevator in the building and there is no way to install one. This means the room is not
      wheelchair accessible and I am not going to describe it as anything other than that.</p>
    <p>Inside, everything happens at floor level. Chairs are available and a chair version of every
      shape in yin and restorative exists; using one is an ordinary option, not a special arrangement.
      The restroom is on the same floor and the door is twenty-nine inches wide.</p>
    <p>The room is dark by design, which suits some people and not others. If low light is difficult
      for you, the lamp by the door can stay on for the whole class and several people have asked for
      exactly that.</p>
