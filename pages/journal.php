    <h2>How these are written</h2>
    <p>I draft from what actually happens in the room, over years rather than weeks. Then, where a
      piece touches anatomy, physiology, sleep or anything a reader might act on medically, it goes to
      Dr. Priya Anand, a physical therapist in Long Island City, who is paid by the hour, holds no
      interest in this studio, and has removed rather more sentences than she has approved.</p>
    <p>That arrangement costs money and slows everything down, and it is the reason there are three
      articles here instead of thirty. It is also the reason I am willing to put my name on them.</p>
    <h2>What will not appear here</h2>
    <p>Anything claiming a posture treats or cures a condition. Anything with the word detox in it.
      Nutritional advice, which is outside what I am qualified to give. Sponsored articles, paid
      placements or guest posts, none of which are accepted, and requests for which are not answered.</p>
    <p>Also, no listicles. Not on principle exactly, but I have never managed to write one about this
      subject that was true.</p>
    <h2>Corrections so far</h2>
    <p>One, in May 2026. An earlier version of the piece on long holds described stretch tolerance as
      a change in the muscle rather than in the nervous system's interpretation, which is a meaningful
      difference and a reader with a physiology background wrote in about it within a day. The page carries
      a dated line at the foot saying so.</p>
    <p>If you find something wrong, write to
      <a href="mailto:rosalind@stillpointyin.com">rosalind@stillpointyin.com</a> with the sentence you
      think is incorrect. Requests are acknowledged within three business days.</p>
  </div>
