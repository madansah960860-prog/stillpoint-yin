    <h2>Three things people ask me to write about</h2>
    <p><strong>Which poses open which emotions.</strong> People do cry in hip shapes, often enough that
      every teacher has a story about it, and I am not going to pretend otherwise. What I will not write
      is that the hip stores grief, because there is no mechanism for that and saying it invites students
      to interpret an ordinary physiological event as a diagnosis. The plainer account is that lying
      still in the dark for an hour, with no task and no screen, is the first quiet many people have had
      in weeks, and quiet is when things arrive. That is worth saying. It does not need an organ attached.</p>
    <p><strong>How to become a yin teacher.</strong> I am asked this perhaps monthly and the answer is
      that I do not run trainings and do not intend to. There are a great many of them and a large share
      exist because a two-hundred-hour course is a more reliable income than a room full of students
      paying twenty-eight dollars. If you want to teach, practise for five years first, then choose a
      training by asking who reads their research rather than who has the best photographs.</p>
    <p><strong>A beginner's guide to yin in ten poses.</strong> This one I have started twice and
      abandoned twice, because the shapes are the least important part and a list of them implies
      otherwise. What matters is how long you stay, what you do with the third minute, and whether you
      can tell sensation from pain. None of that fits in a numbered list, and a numbered list is what
      makes the piece rank, which is precisely the trade I am declining to make.</p>
