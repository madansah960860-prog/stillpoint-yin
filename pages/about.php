<section class="quiet">
  <div class="column">
    <figure>
      <img src="../assets/images/details/details-window-dusk.jpg"
           alt="A window seen from inside a dark room at dusk, the only light in the frame"
           width="900" height="600" loading="lazy" decoding="async">
      <figcaption>The north window at about ten past six in November. For six weeks either
        side of the solstice this is the last daylight the room gets before class.</figcaption>
    </figure>
    <p>Stillpoint opened in March 2022 in a room that had been a dressmaker's workshop, then a
      recording space, then empty for three years. It is on the second floor above a laundromat
      on Java Street, five minutes from the Greenpoint Avenue G, and it has the two qualities I
      was looking for after eighteen months of viewing rooms: no windows facing the street, and
      a landlord willing to let me take the fluorescent fittings out entirely.</p>
    <p>The fluorescents mattered more than anything else. A room lit from a grid of ceiling
      panels cannot be made quiet, whatever you put in it. The lighting here is eleven candles
      along the north wall and one shaded lamp by the door, and in ten months of the year that
      is genuinely all of it.</p>
    <p>The floor is the original maple, sanded once and left alone. The walls are painted a
      color I mixed badly and have grown attached to. There are no mirrors, there is no sound
      system beyond a small speaker that gets used in perhaps half the yin classes, and there is
      nothing on the walls at all.</p>

    <h2>Why only evenings</h2>
    <p>The studio is dark and locked from the end of a class until five the following afternoon.
      People ask about this more than about anything else, usually as a suggestion that I could
      be earning more.</p>
    <p>The straightforward reason is that this practice belongs at the end of a day. A slow class
      at eight in the morning is a perfectly nice thing and it is not what this is. The whole
      proposition — low light, long holds, nothing asked of you — depends on there being a day
      behind you that needs putting down.</p>
    <p>The other reason is that I do not want to run a business that is open all day. I taught six
      classes a day for five years and it made me quite bad at teaching any of them. Eleven classes
      a week is a number I can teach properly, know everybody's name, and still have a life in which
      I am not thinking about yoga.</p>

    <h2>What this place is trying to do</h2>
    <p>Narrowly: to be a reliable dark room where ordinary people can practice slowly for years
      without it becoming a lifestyle, a purchase, or an identity.</p>
    <p>That rules a lot of things out. No challenges, no streaks, no leaderboard and no thirty-day
      anything. No photographs of anybody doing anything impressive, here or anywhere. No talk about
      detoxification, cleansing or releasing stored trauma from a hip, because those claims are not
      supportable and using them would poison the things I do believe. No retreats in Costa Rica.
      No teacher training, ever, because the market is saturated with them and most exist to fund
      the studio rather than to produce teachers.</p>
    <p>It also rules in some slightly boring commitments. A price list with a third off for anyone
      who says they need it, with no proof requested. Two free places on every course. A timetable
      that has not changed in three years. Telling you when a class is canceled rather than letting
      you find out at a locked door.</p>

    <h2>The name</h2>
    <p>A stillpoint is the moment at the end of an exhale, before the next breath starts, when
      nothing is happening. It is also, in the literature, the term for the pause in a pendulum's
      swing. I would like to say I chose it for a considered reason. In fact a student said the word
      in conversation in 2021 and I wrote it on the back of a receipt.</p>
  </div>
