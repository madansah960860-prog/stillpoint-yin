<section class="quiet quiet--slate">
  <div class="column">
    <h2>If it is your first time</h2>
    <p>Come to a yin class rather than a restorative one. This surprises people, who assume
      the softer-sounding option is the gentler introduction. Restorative is so still that a
      first-timer often spends ninety minutes waiting for something to begin. Yin gives you
      enough to do.</p>
    <p>Arrive by twenty past six. The street door is the black one beside the laundromat and
      it sticks; push it harder than feels polite. Come up one flight. Shoes go on the rack at
      the top of the stairs. Everything else you need is in the room already, including socks,
      which most people want by the end.</p>
    <p>Wear something warm and something with sleeves. You will not generate any heat. The
      radiators are original to the building and have views of their own about which evenings
      to work.</p>
    <p>You are allowed to leave at any point. You are allowed to sit up in the middle of a
      five-minute hold and do nothing for the rest of it. Neither of these will be remarked on,
      then or later.</p>
    <p><a class="btn btn--quiet" href="pages/contact.php">How to find the door</a></p>
  </div>
</section>

<section class="quiet">
