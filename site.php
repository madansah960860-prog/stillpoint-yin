    <h2>Learning to Stay</h2>
    <p>Once each season, a six-week course runs on Sunday evenings. It is the only thing here
      that has to be booked, and the only thing that runs in a fixed order, because week four
      genuinely does not work before week three.</p>
    <p>Six sessions, two hours each, twelve people maximum. It covers long holds, the anatomy
      of sensation, what to do with restlessness, slow breathing taught properly, sitting for
      thirty minutes, and finally what to do on the evenings when you are at home alone and
      do not feel like any of it.</p>
