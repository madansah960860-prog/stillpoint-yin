<section class="quiet quiet--slate">
  <div class="column">
    <h2>The opposite of a workout</h2>
    <p>Most of what is sold as yoga in this city is energetic, and there is nothing wrong
      with that. If you want to sweat, there are four excellent studios within a fifteen-minute
      walk of this door and we will name them for you if you ask.</p>
    <p>This is the other thing. In a yin class you will take perhaps six shapes in seventy-five
      minutes, and you will stay in each one for four or five minutes without moving. Nothing
      is repeated. Nothing is counted. There is no sequence to learn and no way to get better
      at it in the sense that people usually mean.</p>
    <p>What happens in those four minutes is the entire subject. The first ninety seconds are
      generally fine. Somewhere after that the mind arrives with a list of things it would
      rather be doing, and the practice, such as it is, consists of staying anyway. People
      describe this as restful afterward and almost never during.</p>
  </div>
</section>

<section class="quiet">
  <div class="column">
    <h2>Three formats</h2>
    <p>All of them run in the evening. None of them is heated. Nobody will adjust your body
      without asking, and the asking happens before the class rather than during it.</p>

    <h3>Yin</h3>
    <p>Seventy-five minutes. Floor-based shapes held for three to five minutes, targeting
      connective tissue through the hips, the lower back and the shoulders. Props hold you
      where you need holding. The holds are long enough that the sensation changes twice
      while you are in them, which is the part worth staying for.</p>

    <h3>Restorative</h3>
    <p>Ninety minutes, and the quietest thing on the schedule. Five or six shapes, each one
      propped so completely that no muscular effort is needed to remain in it, held for eight
      to twelve minutes. You are covered with a blanket. The room is dark. Several people fall
      asleep every single week and nobody is woken.</p>

    <h3>Breath and sitting</h3>
    <p>Sixty minutes on Tuesdays. Twenty-five minutes of slow, unforced breathing, then half
      an hour of sitting, then a few minutes of nothing. There is no breath retention taught
      in this room and there is no forceful breathing. The reasons are on
      <a href="pages/practice.php">the practice page</a> and they are not
      decorative.</p>
  </div>
</section>

